def _load_data(path: str | None) -> list:
    if path:
        with open(path) as f:
            by_day = json.load(f)
        return [d for durations in by_day.values() for d in durations]
    return _EMBEDDED_DATA


def plot(data: list) -> None:
    sorted_data = np.sort(data)
    y = np.arange(1, len(sorted_data) + 1) / len(sorted_data)

    plt.figure(figsize=(10, 6))
    plt.plot(sorted_data, y, marker=".", linestyle="none")
    plt.xscale("log")
    plt.title("Empirical CDF of Telegram FloodWaitError durations", fontsize=20)
    plt.xlabel("Wait duration imposed by Telegram (seconds)", fontsize=14)
    plt.ylabel("Cumulative probability", fontsize=18)
    plt.grid(True)
    plt.tight_layout()
    plt.show()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Plot CDF of FloodWaitError durations")
    parser.add_argument("data_file", nargs="?", default=None,
                        help="JSON produced by extract_fwe.py (omit to use embedded data)")
    args = parser.parse_args()
    plot(_load_data(args.data_file))
